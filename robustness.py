#!/usr/bin/env python3
"""Post-hoc robustness checks, added 2026-10-19 after the Phase A verdict.
None is in the pre-specified analysis plan (preregistration.md, which was never
posted to a registry); summary.md section 8 says why each was added.
Writes results/robustness.md.

  A  the summary.md section 1 decomposition, reproduced (its reading is withdrawn)
  B  why: dose_dolma is mostly the injected route, not "general exposure"
  C  SE sensitivity of the pre-registered CrowS pair-level tests (H1, H2, H3, H5)
  D  exploratory: full-sentence scorer, exemplar gains, SNI membership in StereoSet
"""
import json, numpy as np, pandas as pd, statsmodels.formula.api as smf
from scipy import stats

L = pd.read_csv("results/likelihoods.csv"); V = pd.read_csv("data/variables.csv")
D = L.merge(V, on="sentence_id", how="inner")
for c in ("dolma", "pile", "natinst"): D["l_" + c] = np.log1p(D["dose_" + c])
WRITER = pd.read_csv("data/crows_pairs_anonymized.csv", index_col=0).anon_writer
WRITER.index = [f"crows-{i}" for i in WRITER.index]
WEBB = np.array([-np.sqrt(1.5), -1, -np.sqrt(.5), np.sqrt(.5), 1, np.sqrt(1.5)])
OUT = []
def out(s=""): OUT.append(s); print(s)
fp = lambda p: "<0.001" if p < 0.001 else f"{p:.3f}"

def pairs(scorer):
    """CrowS pair-level frame, one row per (pair, model), as in analysis.py."""
    c = D[D.source_dataset == "crows_pairs"].copy(); c["y"] = c[scorer]
    m = c[c.pair_role == "stereo"].set_index(["pair_id", "model"])
    l = c[c.pair_role == "antistereo"].set_index(["pair_id", "model"])
    j = m.join(l, rsuffix="_l", how="inner")
    P = pd.DataFrame(dict(d_logp=j.y - j.y_l, d_dose=j.l_dolma - j.l_dolma_l,
                          d_pile=j.l_pile - j.l_pile_l,
                          d_len=j.sentence_length_words - j.sentence_length_words_l,
                          bias_type=j.bias_type, arm=j.arm)).reset_index()
    P["writer"] = P.pair_id.map(WRITER)
    return P

def sentence_gain(scorer):
    """Sentence-level frame: same sentence's logp under OLMo v1.7 minus v1.5."""
    W = L.pivot_table(index="sentence_id", columns="model", values=scorer)
    S = V.set_index("sentence_id").join((W["olmo-7b-v1.7"] - W["olmo-7b-v1.5"]).rename("gain"))
    for c in ("dolma", "pile", "natinst"): S["l_" + c] = np.log1p(S["dose_" + c])
    return S.reset_index()

# ------------------------------------------------------------ SE machinery
def cr1_var(X, e, g, A):
    """CR1 variance of each coefficient, with statsmodels' small-sample factor."""
    G, (N, K) = g.max() + 1, X.shape
    S = np.zeros((G, K)); np.add.at(S, g, A.T * e[:, None])
    return G / (G - 1) * (N - 1) / (N - K) * (S ** 2).sum(0)

def wcr(X, y, g, k, B=9999, seed=20261019):
    """Restricted wild cluster bootstrap p for H0: beta_k = 0, Webb six-point
    weights (the recommended choice below ~12 clusters). Vectorised: with
    A = pinv(X) and restricted residuals u, each draw v gives beta*_k = MG[k].v
    and CR1 cluster scores Q v, so no regression is refitted."""
    G, (N, K) = g.max() + 1, X.shape
    A = np.linalg.pinv(X); b = A @ y
    t_obs = b[k] / np.sqrt(cr1_var(X, y - X @ b, g, A)[k])
    Xr = np.delete(X, k, 1); u = y - Xr @ (np.linalg.pinv(Xr) @ y)
    MG = np.zeros((G, K)); np.add.at(MG, g, (A * u).T); MG = MG.T
    P = np.zeros((G, K)); np.add.at(P, g, A[k][:, None] * X)
    Q = np.diag(MG[k]) - P @ MG
    v = np.random.default_rng(seed).choice(WEBB, size=(B, G))
    t = (v @ MG[k]) / np.sqrt(G / (G - 1) * (N - 1) / (N - K) * ((v @ Q.T) ** 2).sum(1))
    return (np.abs(t) >= abs(t_obs)).mean()

def test(X, y, s, k):
    """beta_k and p under five SE choices. p_prereg is the planned one
    (preregistration.md: CR1 on bias_type, normal reference); reproduces analysis.py."""
    A = np.linalg.pinv(X); b = A @ y; e = y - X @ b; r = dict(beta=b[k])
    for name in ("bias_type", "pair_id", "writer"):
        g = pd.factorize(s[name])[0]; G = g.max() + 1
        t = b[k] / np.sqrt(cr1_var(X, e, g, A)[k])
        if name == "bias_type":
            r.update(p_prereg=2 * stats.norm.sf(abs(t)), p_t=2 * stats.t.sf(abs(t), G - 1),
                     p_wcr=wcr(X, y, g, k), G=G)
        else:
            r["p_" + name] = 2 * stats.t.sf(abs(t), G - 1); r["G_" + name] = G
    return r

def X_single(s): return np.column_stack([np.ones(len(s)), s.d_dose, s.d_pile, s.d_len]), 1
def X_did(s):
    """analysis.py's H3 formula minus its duplicate column (contam == C(model))."""
    c = (s.arm == "contaminated").astype(float).values
    return np.column_stack([np.ones(len(s)), c, s.d_dose, s.d_dose * c, s.d_pile, s.d_len]), 3

# ------------------------------------------------------------ report
out("# Robustness checks (post hoc, not in the analysis plan)")
out()
out("Generated by `robustness.py`. Added 2026-10-19; see `summary.md` section 8.")
out("Every section here departs from the pre-specified plan in `preregistration.md`.")

out("\n## A. The summary.md section 1 decomposition, reproduced\n")
out("Outcome: the same sentence's log-likelihood under OLMo v1.7 minus v1.5 (n = 9,334).")
out("Model: `gain ~ log1p(dose_natinst) + log1p(dose_dolma) + log1p(dose_pile) + length`,")
out("CR1 on bias_type, as in summary.md. The August table used the double-counted")
out("`dose_natinst` (fixed 2026-10-19), so the `dose_natinst` row differs slightly from it.\n")
out("| scorer | beta dose_natinst (p) | beta dose_dolma (p) | beta dose_pile (p) |")
out("|---|---|---|---|")
for scorer in ("logp_sum", "logp_mean"):
    S = sentence_gain(scorer)
    r = smf.ols("gain ~ l_natinst + l_dolma + l_pile + sentence_length_words", data=S).fit(
        cov_type="cluster", cov_kwds={"groups": pd.factorize(S.bias_type)[0]})
    out(f"| {scorer} | " + " | ".join(f"{r.params[v]:+.3f} ({fp(r.pvalues[v])})"
                                       for v in ("l_natinst", "l_dolma", "l_pile")) + " |")

out("\n## B. Why the section 1 reading is withdrawn\n")
S = sentence_gain("logp_sum")
inn, oth = S[S.dose_natinst >= 1], S[S.dose_natinst == 0]
r2 = smf.ols("l_natinst ~ l_dolma + l_pile + sentence_length_words", data=S).fit().rsquared
out(f"- Present in Dolma v1.7 (dose_dolma >= 1): **{(inn.dose_dolma >= 1).mean()*100:.1f}%** of "
    f"sentences in the NatInst files (n = {len(inn):,}) vs **{(oth.dose_dolma >= 1).mean()*100:.1f}%** "
    f"of the rest (n = {len(oth):,}).")
out(f"- corr(log1p dose_dolma, log1p dose_natinst) = {S[['l_dolma', 'l_natinst']].corr().iloc[0, 1]:.2f}; "
    f"VIF of dose_natinst in the section A model = {1 / (1 - r2):.1f}.")
out("- So `dose_dolma` is predominantly the injected route measured in the training corpus,")
out("  not 'general v1.7 exposure'. The coefficient on `dose_natinst` holding `dose_dolma` fixed")
out("  is a contrast between two strongly correlated counts of the same copies, and cannot show")
out("  that the route leaves likelihood unmoved. The planned tests in section C do not depend on it.")

out("\n## C. SE sensitivity of the planned CrowS pair-level tests\n")
out("`p_prereg` = CR1 on bias_type with a normal reference, as specified in preregistration.md")
out("(reproduces analysis.py). With this few clusters that reference over-rejects; the alternatives are")
out("CR1 on bias_type with t(G-1), a restricted wild cluster bootstrap on bias_type (Webb")
out("weights, B = 9,999), heteroskedasticity-robust by pair, and CR1 on CrowS writer (t(G-1)).\n")
out("| scorer | test | n | beta | p_prereg | p t(G-1) | p wild boot | p pair-robust | p writer | G bias / writer |")
out("|---|---|---|---|---|---|---|---|---|---|")
for scorer in ("logp_sum", "logp_mean"):
    P = pairs(scorer); tests = []
    for mdl in sorted(P.model.unique()):
        s = P[P.model == mdl]; tests.append((("H1 " if s.arm.iloc[0] == "contaminated" else "H2 ") + mdl, s, X_single))
    tests.append(("H3 DiD v1.7 - v1.5", P[P.model.str.startswith("olmo")], X_did))
    for mdl in sorted(P.model.unique()):
        s = P[P.model == mdl]; tests.append((f"H5 {mdl} top decile", s[s.d_dose.abs() >= s.d_dose.abs().quantile(.9)], X_single))
    for lab, s, mk in tests:
        X, k = mk(s); r = test(X, s.d_logp.values, s, k)
        out(f"| {scorer} | {lab} | {len(s)} | {r['beta']:+.3f} | {fp(r['p_prereg'])} | {fp(r['p_t'])} | "
            f"{fp(r['p_wcr'])} | {fp(r['p_pair_id'])} | {fp(r['p_writer'])} | {r['G']} / {r['G_writer']} |")

out("\n## D. Exploratory checks\n")
out("### D1. Full-sentence scorer\n")
out("Both planned scorers skip the swapped words in CrowS. `full_logp_sum` scores every")
out("token, so a memorised member would show up at the swapped word itself.\n")
out("| test | n | beta | p pair-robust | p wild boot |")
out("|---|---|---|---|---|")
P = pairs("full_logp_sum")
for mdl in sorted(P.model.unique()):
    s = P[P.model == mdl]; X, k = X_single(s); r = test(X, s.d_logp.values, s, k)
    out(f"| {mdl} | {len(s)} | {r['beta']:+.3f} | {fp(r['p_pair_id'])} | {fp(r['p_wcr'])} |")
s = P[P.model.str.startswith("olmo")]; X, k = X_did(s); r = test(X, s.d_logp.values, s, k)
out(f"| DiD v1.7 - v1.5 | {len(s)} | {r['beta']:+.3f} | {fp(r['p_pair_id'])} | {fp(r['p_wcr'])} |")

out("\n### D2. The highest-dose exemplars: likelihood gain from OLMo v1.5 to v1.7\n")
out("| sentence | dose_dolma | gain, scored tokens | gain, full sentence |")
out("|---|---|---|---|")
G1, G2 = sentence_gain("logp_sum").set_index("sentence_id"), sentence_gain("full_logp_sum").set_index("sentence_id")
top_ss = G1[(G1.source_dataset == "stereoset") & (G1.is_natinst_exemplar == 1)].dose_dolma.idxmax()
for sid in ("crows-0-more", "crows-0-less", "crows-50-more", "crows-50-less", top_ss):
    out(f"| `{sid}` | {G1.loc[sid, 'dose_dolma']} | {G1.loc[sid, 'gain']:+.2f} | {G2.loc[sid, 'gain']:+.2f} |")
pct = lambda G: (G[G.source_dataset == "stereoset"].gain < G.loc[top_ss, "gain"]).mean() * 100
out(f"\n`{top_ss}` (\"{G1.loc[top_ss, 'sentence_text']}\") sits at the {pct(G1):.0f}th percentile of")
out(f"StereoSet gains on scored tokens and the {pct(G2):.0f}th on the full sentence.")

out("\n### D3. Does being in the leaked files raise a sentence's gain? (StereoSet)\n")
out("Within StereoSet instances where SNI membership varies between the three sentences;")
out("instance fixed effects, role, length and Pile dose as controls; CR1 on instance. The")
out("v1.5 and Pythia rows are placebos: neither model saw the copies, so a non-zero `in_sni`")
out("there is selection into the SNI files, not exposure.\n")
out("| scorer | outcome | beta in_sni | 95% CI | p | n sentences / instances |")
out("|---|---|---|---|---|---|")
ss = json.load(open("data/stereoset_dev.json"))["data"]["intrasentence"]
INST = {f"ss-{s['id']}": i["id"] for i in ss for s in i["sentences"]}
for scorer in ("logp_sum", "logp_mean"):
    W = L.pivot_table(index="sentence_id", columns="model", values=scorer)
    T = V[V.source_dataset == "stereoset"].set_index("sentence_id").join(W)
    T["gain"] = T["olmo-7b-v1.7"] - T["olmo-7b-v1.5"]
    T["inst"] = T.index.map(INST); T["in_sni"] = (T.dose_natinst >= 1).astype(float)
    T["l_pile"] = np.log1p(T.dose_pile)
    T = T[T.groupby("inst").in_sni.transform("std") > 0]
    for y, lab in (("gain", "gain v1.7 - v1.5"), ("olmo-7b-v1.5", "level, OLMo v1.5 (placebo)"),
                   ("pythia-6.9b", "level, Pythia (placebo)")):
        d = T.assign(yy=T[y])
        for c in ("yy", "in_sni", "l_pile", "sentence_length_words"):
            d[c] = d[c] - d.groupby("inst")[c].transform("mean")
        r = smf.ols("yy ~ in_sni + l_pile + sentence_length_words + C(pair_role) - 1", data=d).fit(
            cov_type="cluster", cov_kwds={"groups": pd.factorize(d.inst)[0]})
        lo, hi = r.conf_int().loc["in_sni"]
        out(f"| {scorer} | {lab} | {r.params.in_sni:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {fp(r.pvalues.in_sni)} | "
            f"{len(d):,} / {d.inst.nunique():,} |")

out("\n### D4. How far could exposure have moved the CrowS score?\n")
s = pairs("logp_sum"); s = s[s.model == "olmo-7b-v1.7"]; tie = s.d_logp == 0
full = pairs("full_logp_sum")
out(f"Under the planned scorers, {tie.sum()} of {len(s):,} CrowS pairs are exact ties: nothing is")
out("scored after the swapped word, and the scored tokens before it share a left context, so")
out("both members get identical log-probabilities in any causal LM. No exposure effect can")
out("break such a tie, so ties are held fixed below. The planned score counts ties as")
out(f"non-stereotypical; excluding them moves OLMo v1.7 from {(s.d_logp > 0).mean()*100:.2f} to "
    f"{(s.d_logp[~tie] > 0).mean()*100:.2f}. The full-sentence scorer has "
    f"{int((full.d_logp == 0).sum())} ties.\n")
out("The H3 DiD does not exclude the planned +0.2, so state the null as a bound: remove an")
out("exposure effect at either end of the DiD's 95% CI (widest of the bias_type / pair / writer")
out("SEs) from OLMo v1.7's untied pair differences and recompute its CrowS score.\n")
out("| scorer | DiD beta | 95% CI (SE used) | CrowS v1.7 | score with effect removed, at CI ends |")
out("|---|---|---|---|---|")
for scorer in ("logp_sum", "logp_mean"):
    P = pairs(scorer); o = P[P.model.str.startswith("olmo")]
    X, k = X_did(o); y = o.d_logp.values; A = np.linalg.pinv(X); b = A @ y; e = y - X @ b
    se = {n: np.sqrt(cr1_var(X, e, pd.factorize(o[n])[0], A)[k]) for n in ("bias_type", "pair_id", "writer")}
    wide = max(se, key=se.get); lo, hi = b[k] - 1.96 * se[wide], b[k] + 1.96 * se[wide]
    s = P[P.model == "olmo-7b-v1.7"]; tie = s.d_logp == 0
    score = lambda bb: (((s.d_logp - bb * s.d_dose) > 0) & ~tie).mean() * 100
    out(f"| {scorer} | {b[k]:+.3f} | [{lo:+.3f}, {hi:+.3f}] ({wide}) | {score(0):.2f} | "
        f"{score(lo):.2f} to {score(hi):.2f} |")

open("results/robustness.md", "w").write("\n".join(OUT) + "\n")
print("\nwrote results/robustness.md")
